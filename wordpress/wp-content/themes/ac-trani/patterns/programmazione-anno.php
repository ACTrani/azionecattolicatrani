	<h2 class="wp-block-heading">L'icona biblica</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>Nel nuovo anno associativo l’Azione Cattolica a livello nazionale riflette sul verbo «generare». Tra le pagine del Vangelo in cui Gesù ribalta la prospettiva dei discepoli c’è quella in cui alcuni si scandalizzano perché i suoi discepoli non digiunano: la tavola diventa il luogo della nuova alleanza, e questo rischia di disorientare i più osservanti.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>Gesù ci consegna una nuova immagine di discepolo: non più uomini e donne incastrati nel ritualismo, ma persone capaci di assaporare con gioia la presenza del Maestro e di guardare lontano senza paura del passato. La Gioia e la Bellezza — il vino e il vestito — vanno custodite in una continua novità.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading {"style":{"spacing":{"margin":{"top":"var:preset|spacing|70"}}}} -->
	<h2 class="wp-block-heading" style="margin-top:var(--wp--preset--spacing--70)">Dalla lettera della Presidente</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph {"fontSize":"grande"} -->
	<p class="has-grande-font-size">Ogni nuovo anno è un invito ad accogliere il vino nuovo del Vangelo in otri nuovi, lasciandoci rinnovare dal Signore attraverso il cammino dell’Azione Cattolica. Con questo spirito, la Presidenza diocesana è lieta di affidarvi la Programmazione associativa annuale, con l’augurio che possa diventare uno strumento di accompagnamento per la formazione integrale di ogni aderente, dalla più tenera età a quella adultissima.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>È una proposta rivolta a tutti coloro che hanno a cuore il Vangelo: ragazzi, giovani, adulti, aderenti, simpatizzanti e quanti desiderano condividere un percorso di crescita umana e cristiana.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>Per questo la proposta che avete tra le mani non è un semplice calendario di appuntamenti. È un insieme di porte aperte, accessibili a tutti, attraverso le quali ciascuno può lasciarsi incontrare dal Signore, cambiare la propria vita e contribuire a rinnovare quella degli altri, diventando davvero vino nuovo in otri nuovi.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>Questa proposta non è conclusa. Ha bisogno della partecipazione di tutti per diventare vita vissuta, testimonianza concreta, Parola che continua a farsi carne nella storia.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>AppassioniAmoCI a questo cammino. Camminando insieme scopriremo che il Signore rinnoverà il nostro cuore, il nostro stile e il nostro modo di essere discepoli nella Chiesa e nel mondo.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>Buon anno associativo!</p>
	<!-- /wp:paragraph -->

